"""Load, validate, check and sample the context layer."""

from __future__ import annotations

import hashlib
import json
from functools import lru_cache
from pathlib import Path
from typing import Any

import psycopg
import yaml

from lexicon.context.schema import Context, Example, Glossary, Joins, Metric, Rule, Table
from lexicon.settings import CONTEXT_DIR

SAMPLES_FILE = "_samples.yaml"


def _y(path: Path) -> Any:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def load(root: Path = CONTEXT_DIR) -> Context:
    tables = {
        t.table: t for t in (Table.model_validate(_y(p)) for p in sorted((root / "tables").glob("*.yaml")))
    }
    metrics = {m.id: m for m in (Metric.model_validate(x) for x in _y(root / "metrics.yaml")["metrics"])}
    rules = {r.id: r for r in (Rule.model_validate(x) for x in _y(root / "rules.yaml")["rules"])}
    examples: list[Example] = []
    for p in sorted((root / "examples").glob("*.yaml")):
        examples += [Example.model_validate(x) for x in _y(p)["examples"]]
    samples = _y(root / SAMPLES_FILE) if (root / SAMPLES_FILE).exists() else {}
    return Context(
        tables=tables,
        metrics=metrics,
        rules=rules,
        joins=Joins.model_validate(_y(root / "joins.yaml")),
        examples=examples,
        glossary=Glossary.model_validate(_y(root / "glossary.yaml")),
        samples=samples or {},
    )


@lru_cache(maxsize=4)
def cached(root: str = str(CONTEXT_DIR)) -> Context:
    return load(Path(root))


def fingerprint(root: Path = CONTEXT_DIR) -> str:
    """sha256 over every context file, so eval runs can record exactly which context they used."""
    h = hashlib.sha256()
    for p in sorted(root.rglob("*.yaml")):
        h.update(p.relative_to(root).as_posix().encode())
        h.update(p.read_bytes())
    return h.hexdigest()


def db_columns(dsn: str) -> dict[str, dict[str, str]]:
    with psycopg.connect(dsn) as conn:
        rows = conn.execute(
            "select table_schema || '.' || table_name, column_name, data_type from information_schema.columns "
            "where table_schema in ('marts', 'support')"
        ).fetchall()
    out: dict[str, dict[str, str]] = {}
    for t, c, d in rows:
        out.setdefault(t, {})[c] = d
    return out


def check_against_db(ctx: Context, dsn: str) -> list[str]:
    problems: list[str] = []
    db = db_columns(dsn)
    for name, t in ctx.tables.items():
        if name not in db:
            problems.append(f"{name}: table missing in database")
            continue
        for c in t.columns:
            if c.name not in db[name]:
                problems.append(f"{name}.{c.name}: column missing in database")
        for col in db[name]:
            if t.column(col) is None:
                problems.append(f"{name}.{col}: database column has no context entry")
    return problems


def check_against_dbt(ctx: Context, marts_yml: Path) -> list[str]:
    """Marts column descriptions must equal Tally's dbt contract text (ADR-007: one source of truth)."""
    problems: list[str] = []
    models = {m["name"]: m for m in _y(marts_yml)["models"]}
    for name, t in ctx.tables.items():
        if not t.dbt_model:
            continue
        m = models.get(t.name)
        if m is None:
            problems.append(f"{name}: no dbt model {t.name} in {marts_yml}")
            continue
        theirs = {c["name"]: " ".join(c["description"].split()) for c in m["columns"]}
        for c in t.columns:
            if c.override_reason:
                continue
            if theirs.get(c.name) != c.description:
                problems.append(f"{name}.{c.name}: description differs from Tally dbt contract")
    return problems


def sample_values(ctx: Context, dsn: str, limit: int = 10) -> dict[str, dict[str, list[str]]]:
    out: dict[str, dict[str, list[str]]] = {}
    with psycopg.connect(dsn) as conn:
        for name, t in ctx.tables.items():
            for c in t.columns:
                if not c.is_enum or c.pii:
                    continue
                rows = conn.execute(
                    psycopg.sql.SQL(
                        "select {c}::text, count(*) from {s}.{t} where {c} is not null group by 1 order by 2 desc, 1 limit %s"
                    ).format(
                        c=psycopg.sql.Identifier(c.name),
                        s=psycopg.sql.Identifier(t.schema_name),
                        t=psycopg.sql.Identifier(t.name),
                    ),
                    (limit,),
                ).fetchall()
                out.setdefault(name, {})[c.name] = [str(r[0]) for r in rows]
    return out


def write_samples(samples: dict[str, dict[str, list[str]]], root: Path = CONTEXT_DIR) -> None:
    header = "# Generated by `lexicon context sample` from the frozen snapshot. Do not edit by hand.\n"
    (root / SAMPLES_FILE).write_text(
        header + yaml.safe_dump(samples, sort_keys=True, width=110), encoding="utf-8"
    )


def to_json(ctx: Context) -> str:
    return json.dumps(ctx.model_dump(mode="json"), sort_keys=True)
